def fill(t):
    return (t.replace("{C}", random.choice(CHARS))
             .replace("{P}", random.choice(PLACES))
             .replace("{T}", random.choice(TECHS))
             .replace("{O}", random.choice(OBJS)))

def make_para(weights):
    # 一个段落由 2~3 句拼接，句间用全角句号/逗号节奏连接
    n = random.randint(2, 3)
    picked = []
    for _ in range(n):
        kind = random.choices(list(weights.keys()), weights=list(weights.values()))[0]
        picked.append(fill(random.choice(BANKS[kind])))
    # 去掉每句末尾多余标点再拼接，保证中文标点自然
    text = "".join(p.rstrip("。") for p in picked) + "。"
    return text

