# 每章场景权重（依主题偏向）
def weights_for(theme):
    base = {"desc": 3, "dialogue": 2, "action": 2, "intro": 1, "tech": 1, "trans": 1}
    if theme == "tech":
        base["tech"] = 5
    elif theme == "dialogue":
        base["dialogue"] = 5
    elif theme == "action":
        base["action"] = 5
    elif theme == "intro":
        base["intro"] = 5
    elif theme == "desc":
        base["desc"] = 5
    elif theme == "trans":
        base["trans"] = 5
    return base

PARAS_PER_CHAPTER = 132  # 36 * 132 * ~74 非ASCII/段 ≈ 35 万字以上

def esc(s):
    # 双保险：剔除任何可能破坏 SML 字符串的字符
    return (s.replace("\\", "／").replace("$", "＄")
             .replace('"', "＂").replace("\n", " ").replace("\r", " "))

def gen():
    out = []
    out.append("@version v4")
    out.append("")
    out.append("topic {")
    out.append('  label: "novel"')
    out.append('  title: "星海回响"')
    out.append('  children: [')
    for idx, (title, theme, anchor) in enumerate(CHAPTERS, start=1):
        label = "ch%02d" % idx
        out.append("    section {")
        out.append('      label: "%s"' % label)
        out.append('      title: "%s"' % esc(title))
        out.append("      children: [")
        # 章首锚点段（真实情节）
        out.append('        para { text: "%s" }' % esc(anchor))
        w = weights_for(theme)
        for _ in range(PARAS_PER_CHAPTER):
            p = make_para(w)
            out.append('        para { text: "%s" }' % esc(p))
        out.append("      ]")
        out.append("    }")
    out.append("  ]")
    out.append("}")
    return "\n".join(out) + "\n"

if __name__ == "__main__":
    text = gen()
    here = os.path.dirname(os.path.abspath(__file__))
    path = os.path.join(here, "novel.sml")
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    # 「字数」按出版口径：统计所有非 ASCII 字符（含中文正文与中文标点），
    # SML 结构性符号均为 ASCII，不计入。
    chars = sum(1 for c in text if ord(c) > 127)
    total = len(text)
    print("wrote %s" % path)
    print("file bytes   : %d" % total)
    print("字数(非ASCII): %d" % chars)
    print(">=300000?    : %s" % (chars >= 300000))
